package main

// Web serving with FrankenPHP (Caddy + PHP in one process).
//
// One FrankenPHP process runs per PHP version in use. The process for the
// default PHP version is the "front": it listens on ports.http (the port every
// dev domain is mapped to inside Chromium), serves its own projects and
// Adminer, and reverse-proxies projects that use another PHP version to that
// version's process on 127.0.0.1:<phpBase + index>.

import (
	"bytes"
	"fmt"
	"net"
	"net/http"
	"os"
	"os/exec"
	"path/filepath"
	"sort"
	"strconv"
	"strings"
	"sync"
	"time"
)

var webMu sync.Mutex // serialises (re)configuration of the PHP processes

func (a *App) dbAdminHost() string { return "db.quickspin.test" }

func (a *App) instanceName(v string) string {
	if v == a.defaultPHP {
		return "web"
	}
	return "php-" + v
}

// instancePorts returns the HTTP and admin ports of a PHP version's process.
func (a *App) instancePorts(v string) (httpPort, adminPort int) {
	if v == a.defaultPHP {
		return a.cfg.Ports.HTTP, a.cfg.Ports.CaddyAdmin
	}
	i := phpIndex(v)
	return a.cfg.Ports.PHPBase + i, a.cfg.Ports.PHPBase + 50 + i
}

// projectPHP is the PHP version a project actually runs on.
func (a *App) projectPHP(p *Project) string {
	if p.PHP != "" && a.phpInstalled(p.PHP) {
		return p.PHP
	}
	return a.defaultPHP
}

// ---------- php.ini ----------

func (a *App) iniDir(v, mode string) string { return a.data("php", v, mode) }

// writePHPIni writes the server and CLI ini files for a PHP version. They are
// loaded through PHP_INI_SCAN_DIR, so no php.ini next to the binary is needed.
func (a *App) writePHPIni(v string) error {
	dir := a.phpDir(v)
	ext := filepath.Join(dir, "ext")
	slash := func(p string) string { return filepath.ToSlash(p) }
	base := func(cli bool) string {
		var b strings.Builder
		w := func(format string, args ...any) { fmt.Fprintf(&b, format+"\n", args...) }
		w("; Generated by QuickSpin on every start — put your own settings in data/php/custom.ini.")
		w("memory_limit = 512M")
		w("max_execution_time = 300")
		w("max_input_time = 300")
		w("max_input_vars = 10000")
		w("post_max_size = 512M")
		w("upload_max_filesize = 512M")
		w("log_errors = On")
		w("error_log = \"%s\"", slash(a.data("logs", "php-"+v+"-errors.log")))
		w("output_buffering = 4096")
		w("realpath_cache_size = 4096k")
		w("realpath_cache_ttl = 600")
		w("date.timezone = UTC")
		w("session.save_path = \"%s\"", slash(a.data("tmp")))
		w("sys_temp_dir = \"%s\"", slash(a.data("tmp")))
		w("upload_tmp_dir = \"%s\"", slash(a.data("tmp")))
		w("auto_prepend_file = \"%s\"", slash(a.data("php", "quickspin-prepend.php")))
		w("mysqli.default_host = 127.0.0.1")
		w("mysqli.default_port = %d", a.cfg.Ports.MariaDB)
		if ca := a.runtimeP("cacert", "cacert.pem"); exists(ca) {
			w("curl.cainfo = \"%s\"", slash(ca))
			w("openssl.cafile = \"%s\"", slash(ca))
		}
		// The official Windows PHP build ships extensions as DLLs.
		if exists(filepath.Join(ext, "php_mbstring.dll")) {
			w("extension_dir = \"%s\"", slash(ext))
			for _, e := range []string{"bz2", "curl", "exif", "fileinfo", "gd", "gettext", "gmp", "intl", "mbstring", "mysqli", "openssl", "pdo_mysql", "pdo_sqlite", "soap", "sockets", "sodium", "sqlite3", "xsl", "zip"} {
				if exists(filepath.Join(ext, "php_"+e+".dll")) {
					w("extension = %s", e)
				}
			}
			if exists(filepath.Join(ext, "php_opcache.dll")) {
				w("zend_extension = opcache")
			}
		}
		if cli {
			w("memory_limit = 2G")
			w("max_execution_time = 0")
			w("error_reporting = E_ALL & ~E_DEPRECATED & ~E_USER_DEPRECATED")
			w("display_errors = stderr")
			w("opcache.enable_cli = 0")
		} else {
			w("error_reporting = E_ALL")
			w("display_errors = On")
			w("display_startup_errors = On")
			w("opcache.enable = 1")
			w("opcache.memory_consumption = 192")
			w("opcache.max_accelerated_files = 20000")
			w("opcache.validate_timestamps = 1")
			w("opcache.revalidate_freq = 0")
		}
		if x := a.xdebugModule(v); x != "" {
			w("zend_extension = \"%s\"", slash(x))
			if cli {
				w("xdebug.mode = off")
			} else {
				w("xdebug.mode = debug,develop")
				w("xdebug.start_with_request = trigger")
				w("xdebug.client_host = 127.0.0.1")
				w("xdebug.client_port = 9003")
				w("xdebug.log_level = 0")
			}
		}
		custom := a.data("php", "custom.ini")
		if c, err := os.ReadFile(custom); err == nil {
			w("\n; ---- data/php/custom.ini ----")
			b.Write(c)
		} else {
			os.WriteFile(custom, []byte("; Your own php.ini settings for every PHP version, e.g.\n; memory_limit = 1G\n"), 0o644)
		}
		return b.String()
	}
	for _, mode := range []string{"server", "cli"} {
		d := a.iniDir(v, mode)
		if err := os.MkdirAll(d, 0o755); err != nil {
			return err
		}
		if err := writeFileAtomic(filepath.Join(d, "quickspin.ini"), []byte(base(mode == "cli"))); err != nil {
			return err
		}
	}
	return a.writePHPWrapper(v)
}

// writePHPWrapper creates data/php/<v>/bin/php so editors and terminals get a
// regular `php` command (FrankenPHP's own CLI with QuickSpin's ini).
func (a *App) writePHPWrapper(v string) error {
	if isWindows {
		return nil // the Windows build ships php.exe
	}
	p := filepath.Join(a.data("php", v, "bin"), "php")
	script := fmt.Sprintf("#!/bin/sh\nPHP_INI_SCAN_DIR=%s exec %s php-cli \"$@\"\n", shellQuote(a.iniDir(v, "cli")), shellQuote(a.frankenphpExe(v)))
	if err := os.MkdirAll(filepath.Dir(p), 0o755); err != nil {
		return err
	}
	return os.WriteFile(p, []byte(script), 0o755)
}

func shellQuote(s string) string { return "'" + strings.ReplaceAll(s, "'", `'\''`) + "'" }

// phpForEditor is the `php` executable editors should use for a version.
func (a *App) phpForEditor(v string) string {
	if isWindows {
		if p := filepath.Join(a.phpDir(v), "php.exe"); exists(p) {
			return p
		}
		return ""
	}
	return filepath.Join(a.data("php", v, "bin"), "php")
}

// phpCLI builds a CLI command (FrankenPHP's php-cli) for a PHP version.
func (a *App) phpCLI(v string, args ...string) (*exec.Cmd, error) {
	fp := a.frankenphpExe(v)
	if fp == "" {
		return nil, fmt.Errorf("PHP %s is not installed", v)
	}
	if !exists(filepath.Join(a.iniDir(v, "cli"), "quickspin.ini")) {
		if err := a.writePHPIni(v); err != nil {
			return nil, err
		}
	}
	c := exec.Command(fp, append([]string{"php-cli"}, args...)...)
	c.Env = append(os.Environ(),
		"PHP_INI_SCAN_DIR="+a.iniDir(v, "cli"),
		"XDEBUG_MODE=off",
		"WP_CLI_CACHE_DIR="+a.data("cache", "wp-cli"),
		"TMP="+a.data("tmp"), "TEMP="+a.data("tmp"), "TMPDIR="+a.data("tmp"),
	)
	hideCmd(c)
	return c, nil
}

// ---------- Caddyfiles ----------

func (a *App) caddyfileFor(v string) string {
	var b strings.Builder
	w := func(format string, args ...any) { fmt.Fprintf(&b, format+"\n", args...) }
	q := func(p string) string { return strconv.Quote(filepath.ToSlash(p)) }
	httpPort, adminPort := a.instancePorts(v)
	front := v == a.defaultPHP
	threads := a.cfg.PHPWorkers
	if threads < 2 {
		threads = 2
	}
	w("# Generated by QuickSpin for PHP %s — regenerated whenever projects change.", v)
	w("{")
	w("\tadmin 127.0.0.1:%d", adminPort)
	w("\tpersist_config off")
	w("\tauto_https off")
	w("\thttp_port %d", httpPort)
	w("\tdefault_bind 127.0.0.1")
	w("\tstorage file_system %s", q(a.data("web", a.instanceName(v))))
	w("\tgrace_period 2s")
	w("\tfrankenphp {")
	w("\t\tnum_threads %d", threads)
	w("\t}")
	w("}")
	w("")
	if front && exists(a.runtimeP("adminer", "adminer.php")) {
		w("http://%s {", a.dbAdminHost())
		w("\troot * %s", q(a.data("php", "adminer")))
		w("\tphp_server")
		w("}")
		w("")
	}
	projects := a.store.List()
	sort.Slice(projects, func(i, j int) bool { return projects[i].Slug < projects[j].Slug })
	for _, p := range projects {
		if p.Path == "" || len(p.Domains) == 0 {
			continue
		}
		pv := a.projectPHP(p)
		if pv != v && !front {
			continue
		}
		var hosts []string
		for _, d := range p.Domains {
			hosts = append(hosts, "http://"+d)
		}
		if p.Multisite {
			hosts = append(hosts, "http://*."+p.Domains[0])
		}
		w("# %s (PHP %s)", p.Name, pv)
		w("%s {", strings.Join(hosts, ", "))
		if pv != v { // front: hand over to that version's process
			port, _ := a.instancePorts(pv)
			w("\treverse_proxy 127.0.0.1:%d {", port)
			w("\t\tflush_interval -1")
			w("\t}")
		} else {
			w("\troot * %s", q(p.DocRoot()))
			w("\tencode zstd br gzip")
			w("\tphp_server {")
			w("\t\tenv QUICKSPIN_SITE %s", p.Slug)
			w("\t}")
		}
		w("}")
		w("")
	}
	// Anything else (e.g. a domain removed from a project).
	w("http:// {")
	w("\trespond \"QuickSpin: no project uses the domain {host}. Add it on the dashboard: %s\" 404", a.dashboardURL())
	w("}")
	return b.String()
}

// ---------- processes ----------

// startPHPInstance starts (or keeps) the FrankenPHP process for a PHP version.
func (a *App) startPHPInstance(v string) error {
	name := a.instanceName(v)
	if s := a.service(name); s != nil {
		if st := s.Status().State; st == "running" || st == "starting" || st == "restarting" {
			return nil
		}
	}
	exe := a.frankenphpExe(v)
	if exe == "" {
		return fmt.Errorf("PHP %s is not installed", v)
	}
	if err := a.writePHPIni(v); err != nil {
		return err
	}
	cf := a.data("web", name, "Caddyfile")
	if err := writeFileAtomic(cf, []byte(a.caddyfileFor(v))); err != nil {
		return err
	}
	storage := a.data("web", name)
	s := &Service{
		Name: name, AutoRestart: true, InJob: true, Hidden: true,
		Log: NewLogBuf(a.data("logs", name+".log"), 300),
		Build: func() (*exec.Cmd, error) {
			writeFileAtomic(cf, []byte(a.caddyfileFor(v))) // always current, also after a crash
			c := exec.Command(exe, "run", "--config", cf, "--adapter", "caddyfile")
			c.Dir = a.phpDir(v)
			c.Env = append(os.Environ(),
				"PHP_INI_SCAN_DIR="+a.iniDir(v, "server"),
				"XDG_DATA_HOME="+storage, "XDG_CONFIG_HOME="+storage, "AppData="+storage, "HOME="+storage,
				"TMP="+a.data("tmp"), "TEMP="+a.data("tmp"), "TMPDIR="+a.data("tmp"),
			)
			return c, nil
		},
		StopFn: func(cmd *exec.Cmd) { gracefulStop(cmd.Process.Pid) },
	}
	a.addService(s)
	s.Start()
	port, _ := a.instancePorts(v)
	a.logf("Starting FrankenPHP (PHP %s) on 127.0.0.1:%d…", v, port)
	for i := 0; i < 120; i++ { // the binary is large; first start can take a few seconds
		if c, err := net.DialTimeout("tcp", fmt.Sprintf("127.0.0.1:%d", port), 300*time.Millisecond); err == nil {
			c.Close()
			return nil
		}
		if st := s.Status(); st.State == "failed" {
			return fmt.Errorf("FrankenPHP (PHP %s) failed: %s — see %s", v, st.Error, a.data("logs", name+".log"))
		}
		time.Sleep(250 * time.Millisecond)
	}
	return fmt.Errorf("FrankenPHP (PHP %s) did not start — see %s", v, a.data("logs", name+".log"))
}

// startWeb starts the front process and one process per other PHP version in use.
func (a *App) startWeb() error {
	webMu.Lock()
	defer webMu.Unlock()
	if err := a.writeSupportFiles(); err != nil {
		return err
	}
	for _, v := range a.neededPHPVersions() {
		if v == a.defaultPHP {
			continue
		}
		if err := a.startPHPInstance(v); err != nil {
			a.logf("%v", err)
		}
	}
	return a.startPHPInstance(a.defaultPHP)
}

// ensurePHP makes sure the process for a PHP version is running.
func (a *App) ensurePHP(v string) error {
	webMu.Lock()
	defer webMu.Unlock()
	return a.startPHPInstance(v)
}

// reloadWeb pushes fresh configuration to every process (zero downtime),
// starting processes for newly used PHP versions and stopping unused ones.
func (a *App) reloadWeb() error {
	webMu.Lock()
	defer webMu.Unlock()
	if err := a.writeSupportFiles(); err != nil {
		return err
	}
	needed := map[string]bool{}
	for _, v := range a.neededPHPVersions() {
		needed[v] = true
	}
	// Stop processes for PHP versions nobody uses any more.
	a.mu.Lock()
	var unused []*Service
	for n, s := range a.services {
		if v, ok := strings.CutPrefix(n, "php-"); ok && phpIndex(v) >= 0 && !needed[v] {
			unused = append(unused, s)
			delete(a.services, n)
		}
	}
	a.mu.Unlock()
	for _, s := range unused {
		s.Stop(5 * time.Second)
	}
	var firstErr error
	versions := make([]string, 0, len(needed))
	for v := range needed {
		versions = append(versions, v)
	}
	sort.Slice(versions, func(i, j int) bool { return versions[j] == a.defaultPHP }) // front last
	for _, v := range versions {
		if !a.phpInstalled(v) {
			continue
		}
		if s := a.service(a.instanceName(v)); s == nil || !s.Running() {
			if err := a.startPHPInstance(v); err != nil && firstErr == nil {
				firstErr = err
			}
			continue
		}
		if err := a.loadConfig(v); err != nil && firstErr == nil {
			firstErr = err
		}
	}
	return firstErr
}

func (a *App) loadConfig(v string) error {
	content := a.caddyfileFor(v)
	writeFileAtomic(a.data("web", a.instanceName(v), "Caddyfile"), []byte(content))
	if err := a.writePHPIni(v); err != nil {
		return err
	}
	_, admin := a.instancePorts(v)
	req, _ := http.NewRequest("POST", fmt.Sprintf("http://127.0.0.1:%d/load", admin), strings.NewReader(content))
	req.Header.Set("Content-Type", "text/caddyfile")
	resp, err := (&http.Client{Timeout: 30 * time.Second}).Do(req)
	if err != nil {
		if s := a.service(a.instanceName(v)); s != nil {
			s.Restart()
			return nil
		}
		return err
	}
	defer resp.Body.Close()
	if resp.StatusCode != 200 {
		var buf bytes.Buffer
		buf.ReadFrom(resp.Body)
		return fmt.Errorf("FrankenPHP (PHP %s) rejected the configuration: %s", v, strings.TrimSpace(buf.String()))
	}
	return nil
}
